"""Gate G1 evidence from the week-5 baseline artifacts (validation only).

Criterion (docs/protocol/preregistration.md, section 9), fixed before the run:
on HI-Medium validation at the primary budget, the paired 95% CI of
oracle - S0 linked detection excludes 0 and the estimate is at least
:data:`MIN_GAP`.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from finmesh.eval.provenance import read_artifact
from finmesh.reporting import fmt, table

MIN_GAP = 0.05
HEADLINE_DATASET = "HI-Medium"


def _budget(res: dict[str, Any], name: str) -> dict[str, Any]:
    return next(b for b in res["budgets"] if b["budget"] == name)


def gap_summary(result: dict[str, Any]) -> dict[str, Any]:
    primary = result["primary_budget"]
    s0 = _budget(result["results"]["S0-BG"], primary)
    oracle = _budget(result["results"]["oracle"], primary)
    comp = result["comparisons"]
    gap = comp["oracle - S0-BG"]["linked"]["difference"]
    return {
        "dataset": result["dataset"],
        "seed": result["seed"],
        "schemes": s0["schemes"],
        "s0_linked": s0["linked"]["estimate"],
        "s0_random_linked": (s0.get("random_alert_linked") or {}).get("estimate"),
        "oracle_linked": oracle["linked"]["estimate"],
        "oracle_random_linked": (oracle.get("random_alert_linked") or {}).get("estimate"),
        "gap": gap["estimate"],
        "gap_low": gap["low"],
        "gap_high": gap["high"],
        "gap_p_holm": comp["oracle - S0-BG"]["linked"]["p_holm"],
        "criterion_met": gap["low"] > 0 and gap["estimate"] >= MIN_GAP,
        "s0_detected": s0["detected"]["estimate"],
        "oracle_detected": oracle["detected"]["estimate"],
        "detected_gap": comp["oracle - S0-BG"]["detected"]["difference"]["estimate"],
        "s0_auprc": result["results"]["S0-BG"]["window"]["auprc"]["estimate"],
        "oracle_auprc": result["results"]["oracle"]["window"]["auprc"]["estimate"],
        "pt4b_auprc_gain": comp["S0-BG - S0-B"]["window"]["auprc_difference"]["estimate"],
        "pt4b_low": comp["S0-BG - S0-B"]["window"]["auprc_difference"]["low"],
        "pt4b_high": comp["S0-BG - S0-B"]["window"]["auprc_difference"]["high"],
        **_ablation(result, primary),
    }


def _ablation(result: dict[str, Any], primary: str) -> dict[str, Any]:
    """The preregistered artefact ablation, when the artifact has it."""
    pair = result["comparisons"].get("oracle-noart - S0-BG-noart")
    if pair is None:
        return {"ablation_gap": None, "ablation_s0_auprc": None}
    d = pair["linked"]["difference"]
    return {
        "ablation_gap": f"{fmt(d['estimate'])} [{fmt(d['low'])}, {fmt(d['high'])}]",
        "ablation_s0_auprc": result["results"]["S0-BG-noart"]["window"]["auprc"]["estimate"],
    }


def load_summaries(artifacts: Path) -> list[dict[str, Any]]:
    out = []
    for path in sorted(artifacts.glob("baselines_*_seed0.json")):
        prov, result = read_artifact(path)
        if prov.get("fixture"):
            continue  # CC3: fixture artifacts never reach a gate
        out.append(gap_summary(result))
    return out


def render_g1(summaries: list[dict[str, Any]]) -> str:
    head = next((s for s in summaries if s["dataset"] == HEADLINE_DATASET), None)
    verdict = (
        "**no HI-Medium baseline artifact yet**"
        if head is None
        else (
            f"**criterion met** (oracle − S0 linked detection {fmt(head['gap'])}, 95% CI "
            f"[{fmt(head['gap_low'])}, {fmt(head['gap_high'])}])"
            if head["criterion_met"]
            else f"**criterion not met** (oracle − S0 linked detection {fmt(head['gap'])}, 95% CI "
            f"[{fmt(head['gap_low'])}, {fmt(head['gap_high'])}]); record why before week 6"
        )
    )
    rows = [
        {
            **s,
            "gap_ci": f"{fmt(s['gap'])} [{fmt(s['gap_low'])}, {fmt(s['gap_high'])}]",
            "pt4b": f"{fmt(s['pt4b_auprc_gain'])} [{fmt(s['pt4b_low'])}, {fmt(s['pt4b_high'])}]",
        }
        for s in summaries
    ]
    return "\n".join(
        [
            "# G1 evidence · baselines on validation",
            "",
            "Generated by `finmesh g1` from `data/artifacts/week05/baselines_<ds>_seed0.json`. "
            "Criterion (preregistration, section 9): on HI-Medium validation at the primary "
            "budget, the paired 95% CI of oracle − S0 linked detection excludes 0 and the "
            f"estimate is at least {MIN_GAP}.",
            "",
            f"Headline: {verdict}.",
            "",
            table(
                rows,
                [
                    ("dataset", "Dataset"),
                    ("schemes", "Schemes"),
                    ("s0_linked", "S0 linked"),
                    ("s0_random_linked", "Random (local)"),
                    ("oracle_linked", "Oracle linked"),
                    ("oracle_random_linked", "Random (pooled)"),
                    ("gap_ci", "Oracle − S0 [95% CI]"),
                    ("criterion_met", "Criterion"),
                    ("s0_detected", "S0 detected"),
                    ("oracle_detected", "Oracle detected"),
                    ("s0_auprc", "S0 AUPRC"),
                    ("oracle_auprc", "Oracle AUPRC"),
                    ("pt4b", "PT4b: graph − behaviour AUPRC"),
                    ("ablation_gap", "Ablation: oracle − S0 linked"),
                    ("ablation_s0_auprc", "Ablation: S0 AUPRC"),
                ],
            ),
            "",
        ]
    )
